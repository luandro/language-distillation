"""Baseline evaluation on the frozen mzr benchmark v2 (CPU only; no torch needed).

Subcommands
- prepare:   write var/artifacts/baseline_v2/{inputs.json,v0_train.hf.jsonl}; print contamination.
- retrieval: nearest-train-row baseline (input side only) -> predictions/retrieval.json.
- report:    score every predictions/*.json -> results.json and results.md.

Model baselines are generated by scripts/gen_baseline_v2.py (GPU) into predictions/<system>.json.
Scoring needs sacrebleu (+ sentencepiece for spBLEU).
"""

from __future__ import annotations

import argparse
import json
import subprocess
from pathlib import Path
from typing import Any

from langpipe.languages.base import profile_for
from langpipe.training.baseline_eval import (
    BenchmarkSpec,
    NearestRowRetriever,
    Scorer,
    build_rows,
    evaluate_system,
    load_benchmark,
    markdown_table,
    read_jsonl,
    retrieval_predictions,
)

REPO = Path(__file__).resolve().parent.parent
DATASETS = REPO / "exports" / "mzr" / "datasets"
OUT = REPO / "var" / "artifacts" / "baseline_v2"
V0_COMMIT = "9aa157f"  # snapshot of the export the published adapter was trained on
SET_NAMES = ("val", "test", "chant_val", "chant_test")

# This script is the mzr benchmark's entry point, so the codes it names are data here.
_PROFILE = profile_for("mzr")
CONTACT = "por"
SPEC = BenchmarkSpec(
    target=_PROFILE.language,
    contact=CONTACT,
    chant_provenances=frozenset(_PROFILE.chant_provenances),
)
DIRECTIONS = SPEC.directions()


def _v0_train() -> list[dict[str, Any]]:
    path = OUT / "v0_train.hf.jsonl"
    if not path.exists():
        OUT.mkdir(parents=True, exist_ok=True)
        blob = subprocess.run(
            ["git", "show", f"{V0_COMMIT}:exports/mzr/datasets/train.hf.jsonl"],
            cwd=REPO,
            check=True,
            capture_output=True,
        ).stdout
        path.write_bytes(blob)
    return read_jsonl(path)


def cmd_prepare(_: argparse.Namespace) -> None:
    sets = load_benchmark(DATASETS, SPEC, _v0_train())
    uniq: dict[str, dict[str, str]] = {}
    for rows in sets.values():
        for r in rows:
            uniq[r.id] = {
                "id": r.id,
                SPEC.target: r.side(SPEC.target),
                SPEC.contact: r.side(SPEC.contact),
            }
    (OUT / "inputs.json").write_text(
        json.dumps(list(uniq.values()), ensure_ascii=False), encoding="utf-8"
    )
    flags = {
        s: {"n": len(rows), "v0_overlap": sum(r.in_v0_train for r in rows)}
        for s, rows in sets.items()
    }
    flagged = {s: [r.id for r in rows if r.in_v0_train] for s, rows in sets.items()}
    (OUT / "v0_overlap_flags.json").write_text(
        json.dumps({"counts": flags, "flagged_ids": flagged}, indent=1), encoding="utf-8"
    )
    print(f"{len(uniq)} unique rows -> {OUT / 'inputs.json'}")
    print(json.dumps(flags))


def _save(system: str, preds: dict[str, dict[str, str]], meta: dict[str, Any]) -> None:
    path = OUT / "predictions" / f"{system}.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps({"system": system, "meta": meta, "predictions": preds}, ensure_ascii=False),
        encoding="utf-8",
    )
    print(f"wrote {path}")


def cmd_retrieval(_: argparse.Namespace) -> None:
    train_raw = [
        r
        for r in read_jsonl(DATASETS / "train.hf.jsonl")
        if not r["provenance"].startswith("synthetic:")
    ]
    retriever = NearestRowRetriever(build_rows(train_raw, SPEC), SPEC)
    sets = load_benchmark(DATASETS, SPEC)
    preds: dict[str, dict[str, str]] = {d: {} for d in DIRECTIONS}
    exact = 0
    seen: set[str] = set()
    for rows in sets.values():
        for d in DIRECTIONS:
            for r, h in zip(rows, retrieval_predictions(retriever, rows, d), strict=True):
                preds[d][r.id] = h
        for r in rows:
            if r.id not in seen:
                seen.add(r.id)
                exact += (
                    retriever.nearest(r.side(SPEC.target), SPEC.target)[2]
                    + retriever.nearest(r.side(SPEC.contact), SPEC.contact)[2]
                )
    meta = {
        "train_rows": len(retriever.train),
        "excluded": "synthetic:* train rows",
        "similarity": "exact folded key, else cosine of char 3-gram TF-IDF on folded input side",
        "exact_key_hits_input_side": exact,
    }
    _save("retrieval", preds, meta)
    print(meta)


def cmd_report(args: argparse.Namespace) -> None:
    sets = load_benchmark(DATASETS, SPEC, _v0_train())
    scorer = Scorer()
    systems: dict[str, Any] = {}
    metas: dict[str, Any] = {}
    for path in sorted((OUT / "predictions").glob("*.json")):
        blob = json.loads(path.read_text(encoding="utf-8"))
        system = blob["system"]
        metas[system] = blob.get("meta", {})
        per_dir = {
            d: {s: {r.id: blob["predictions"][d][r.id] for r in sets[s]} for s in SET_NAMES}
            for d in blob["predictions"]
            if all(r.id in blob["predictions"][d] for s in SET_NAMES for r in sets[s])
        }
        print(f"scoring {system} ({', '.join(per_dir)})", flush=True)
        systems[system] = evaluate_system(sets, per_dir, scorer, n_boot=args.n_boot)
    overlap = {s: sum(r.in_v0_train for r in rows) for s, rows in sets.items()}
    results = {
        "benchmark_version": 2,
        "metrics": "sacreBLEU chrF++ (word_order=2) primary; spBLEU (flores200) secondary",
        "sacrebleu_signature": {
            "chrf": str(scorer.chrf.get_signature()),
            "spbleu": str(scorer.bleu.get_signature()),
        },
        "bootstrap": {
            "n_resamples": args.n_boot,
            "ci": "95% percentile",
            "unit": "component for chant rows with a component; row otherwise",
        },
        "v0_overlap_rows": overlap,
        "v0_overlap_note": (
            "in_v0_train = a row's Marubo or Portuguese folded key occurs in the published "
            "adapter's training data (commit 9aa157f). Only meaningful for old_adapter scores; "
            "see slices v0_overlap:true / v0_overlap:false."
        ),
        "v0_overlap_ids": {s: [r.id for r in rows if r.in_v0_train] for s, rows in sets.items()},
        "system_meta": metas,
        "systems": systems,
    }
    (OUT / "results.json").write_text(json.dumps(results, ensure_ascii=False, indent=1), "utf-8")
    parts = [
        "# Baseline results, benchmark v2 (chrF++ [95% CI], n rows)\n",
        "Direction names the target. CIs: bootstrap by row (Bible) or by component (chant).\n",
    ]
    cols = ("all", "bible", "chant", "v0_overlap:false")
    for s, title in (("test", "Primary test"), ("val", "Primary val")):
        parts += [f"## {title}\n", markdown_table(results, s, cols), ""]
    for s, title in (("chant_test", "Chant benchmark test"), ("chant_val", "Chant benchmark val")):
        parts += [
            f"## {title}\n",
            markdown_table(results, s, ("all", "v0_overlap:true", "v0_overlap:false")),
            "",
        ]
    parts += ["## Per-source (primary test)\n"]
    srcs = sorted({r.provenance for r in sets["test"]})
    parts += [markdown_table(results, "test", tuple(f"source:{p}" for p in srcs)), ""]
    (OUT / "results.md").write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT / 'results.json'} and results.md")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("prepare").set_defaults(fn=cmd_prepare)
    sub.add_parser("retrieval").set_defaults(fn=cmd_retrieval)
    rp = sub.add_parser("report")
    rp.add_argument("--n-boot", type=int, default=1000)
    rp.set_defaults(fn=cmd_report)
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
